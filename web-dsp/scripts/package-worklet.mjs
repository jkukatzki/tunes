// Create one self-contained worklet script so every dependency shares the
// distribution's cache/version URL. No top-level await, blob URLs, or fetch in
// AudioWorkletGlobalScope. Only synchronous wasm-bindgen initialization is used.
import { readFile, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const directory = resolve(process.argv[2]);
const web = fileURLToPath(new URL("../web/", import.meta.url));
let bindings = await readFile(join(directory, "tunes_web_dsp.js"), "utf8");
if (
  !bindings.includes("export class DspWorker") ||
  !bindings.includes("export { initSync, __wbg_init as default };")
)
  throw new Error(
    "Unexpected wasm-bindgen exports; update the worklet packager",
  );
// The glue is inlined into a function scope, where any `export` is a syntax
// error. Dependencies can add exports of any form (cpal's wasm-bindgen feature
// adds `export const SampleFormat`), so strip every declaration form.
const exportDeclaration = /^export (?=(?:async\s+)?(?:class|function|const|let|var)\b)/gm;
bindings = bindings
  .replace(exportDeclaration, "")
  .replace("export { initSync, __wbg_init as default };", "");
// Only the WASM getrandom import uses this function in the generated glue.
bindings = bindings.replaceAll(
  "globalThis.crypto.getRandomValues(",
  "workletEntropy.fill(",
);
const entropy = (
  await readFile(join(web, "worklet-entropy.mjs"), "utf8")
).replace("export class ", "class ");
const encoder = (
  await readFile(join(web, "worklet-utf8.mjs"), "utf8")
).replaceAll("export class ", "class ");
const render = (await readFile(join(web, "render-buffer.mjs"), "utf8")).replace(
  "export function ",
  "function ",
);
const processor = (
  await readFile(join(web, "dsp-worklet.mjs"), "utf8")
).replace("export function ", "function ");
const worklet = `// Generated by package-worklet.mjs; do not edit.\n${encoder}\n${entropy}\nconst workletEntropy = new WorkletEntropy();\nconst bindings = (() => {\nconst TextEncoder = globalThis.TextEncoder ?? WorkletTextEncoder;\nconst TextDecoder = globalThis.TextDecoder ?? WorkletTextDecoder;\n${bindings}\nreturn { initSync, DspWorker };\n})();\n${render}\n${processor}\nregisterProcessor("tunes-dsp", createDspProcessor({ ...bindings, createBlockRenderer, entropy: workletEntropy }));\n`;
// Fail the build, not the browser: addModule only reports a parse error.
const leftover = worklet.match(/^\s*export\b.*$/m);
if (leftover)
  throw new Error(
    `Unhandled export in packaged worklet; update the worklet packager: ${leftover[0].trim()}`,
  );
await writeFile(join(directory, "dsp-worklet.js"), worklet);
